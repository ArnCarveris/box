#!/usr/bin/env python3
"""Builds the audio core into the standalone wasm the web build runs in an AudioWorklet.

Usage: audio_core.py <core.c> <out dir> <project dir>   (bake3 rule of project.json)

bake3 runs it for src/audio/core/core.c before it compiles box, for every target. For a target
other than Emscripten (the out dir of the build has no "Emscripten" in it) it does nothing. For
Emscripten it compiles the C files of the folder of core.c with emcc into box_audio_core.wasm in
the out dir, a module without imports and with its own memory, and writes its bytes as a C array
to <project>/.bake/generated/box_audio_core_wasm.h, which src/audio/platform_web.c includes, so
the core travels inside the main module and the page needs no extra file.

The core is built with -O2 whatever the configuration of the build, so every configuration
embeds the same bytes. The header is rewritten only when the bytes change, and the build is
skipped while a stamp is newer than the sources and this script.
"""
import os
import shutil
import subprocess
import sys
import tempfile

EXPORTS = [
    "box_audio_core_wasm_init",
    "box_audio_core_wasm_render",
    "box_audio_core_wasm_left",
    "box_audio_core_wasm_right",
    "box_audio_core_wasm_set_frequency",
    "box_audio_core_wasm_set_level",
]

FLAGS = [
    "-O2", "-msimd128", "-std=c11", "-DBOX_AUDIO_CORE_WASM", "--no-entry",
    "-sSTANDALONE_WASM", "-sINITIAL_MEMORY=1MB", "-sSTACK_SIZE=64KB",
    "-sALLOW_MEMORY_GROWTH=0", "-sFILESYSTEM=0",
    "-sEXPORTED_FUNCTIONS=" + ",".join("_" + name for name in EXPORTS),
]


def find_emcc():
    """Finds emcc on PATH, else in $EMSDK."""
    emcc = os.environ.get("EMCC") or shutil.which("emcc")
    if not emcc:
        for var in ("EMSDK", "EMSDK_DIR"):
            root = os.environ.get(var)
            path = os.path.join(root, "upstream", "emscripten", "emcc") if root else None
            if path and os.path.exists(path):
                emcc = path
                break
    return emcc


def newest(paths):
    """The newest modification time of the paths."""
    return max(os.path.getmtime(path) for path in paths)


def write_if_changed(path, text):
    """Writes text to path unless it holds it already, through a rename so a concurrent build
    never reads half a file."""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return
    tmp = f"{path}.{os.getpid()}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def header(data):
    """The C header that holds the bytes of the wasm."""
    lines = [
        "/* Generated by tools/audio_core.py from src/audio/core, do not edit. */",
        "",
        "/** Bytes of the standalone wasm of the audio core */",
        "static const unsigned char box_audio_core_wasm[] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source, out_dir, project = argv
    if "Emscripten" not in out_dir:
        return 0

    core_dir = os.path.dirname(os.path.abspath(source))
    sources = sorted(os.path.join(core_dir, name) for name in os.listdir(core_dir)
        if name.endswith(".c"))
    inputs = sources + [os.path.join(core_dir, name) for name in os.listdir(core_dir)
        if name.endswith(".h")] + [os.path.abspath(__file__)]
    gen_dir = os.path.join(project, ".bake", "generated")
    os.makedirs(gen_dir, exist_ok=True)
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(gen_dir, "box_audio_core_wasm.h")
    stamp = os.path.join(gen_dir, "box_audio_core_wasm.stamp")
    wasm = os.path.join(out_dir, "box_audio_core.wasm")
    if (os.path.exists(target) and os.path.exists(stamp) and os.path.exists(wasm)
            and os.path.getmtime(stamp) >= newest(inputs)):
        return 0

    emcc = find_emcc()
    if not emcc:
        print("audio_core.py: emcc not found, cannot build the audio core", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory(dir=out_dir) as tmp:
        built = os.path.join(tmp, "box_audio_core.wasm")
        result = subprocess.run([emcc] + FLAGS + sources + ["-o", built])
        if result.returncode != 0:
            print("audio_core.py: emcc failed to build the audio core", file=sys.stderr)
            return 1
        with open(built, "rb") as f:
            data = f.read()
        os.replace(built, wasm)

    write_if_changed(target, header(data))
    with open(f"{stamp}.{os.getpid()}.tmp", "w", encoding="utf-8") as f:
        f.write(f"{len(data)}\n")
    os.replace(f"{stamp}.{os.getpid()}.tmp", stamp)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
